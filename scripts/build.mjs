// A dependency-free, reproducible single-file HACS distribution.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
export async function buildBundle() {
  const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  let source = await readFile(resolve(root, 'src/tessie-card.js'), 'utf8');
  const data = await readFile(resolve(root, 'src/vehicle-artwork-data.js'), 'utf8');
  let artwork = await readFile(resolve(root, 'src/vehicle-artwork.js'), 'utf8');
  artwork = artwork.replace(/^import[^\n]*\n/m, '').replace(/^export \{ ARTWORK, ARTWORK_IMAGES \};\n/m, '');
  source = source.replace(/^import[^\n]*vehicle-artwork\.js';\n/m, '');
  source = `${data}\n${artwork}\n${source}`;
  if (!source.includes(`export const VERSION = "${pkg.version}"`)) throw new Error('Source and package versions differ.');
  const matches = [...source.matchAll(/new URL\("\.\.\/assets\/vehicles\/([a-f0-9]+\.webp)",import\.meta\.url\)\.href/g)];
  for (const match of matches) {
    const bytes = await readFile(resolve(root, 'assets/vehicles', match[1]));
    if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') throw new Error(`Invalid WebP: ${match[1]}`);
    source = source.replace(match[0], JSON.stringify(`data:image/webp;base64,${bytes.toString('base64')}`));
  }
  if (!matches.length) throw new Error('No prepared artwork found.');
  return `/* GENERATED by node scripts/build.mjs. Edit src/tessie-card.js instead. */\n${source}`;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bundle = await buildBundle();
  const destination = resolve(root, 'tessie-card.js');
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== bundle) throw new Error('Distribution is stale. Run node scripts/build.mjs.');
    console.log('HACS distribution is up to date.');
  } else {
    await writeFile(destination, bundle);
    console.log(`Built tessie-card.js (${Buffer.byteLength(bundle)} bytes, artwork embedded).`);
  }
}
